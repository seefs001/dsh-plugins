function buildTheme(kind, basePalette, overrides = {}) {
  const palette = { ...basePalette, ...overrides }
  const isDark = kind === 'dark'
  const chartPalette = isDark
    ? {
      primary: palette.accentPrimary,
      secondary: '#2dd4bf',
      tertiary: '#a78bfa',
      quaternary: '#fbbf24',
      positive: '#34d399',
      negative: '#f87171',
      neutral: '#94a3b8',
      grid: palette.strokeTertiary,
      axis: palette.textTertiary,
    }
    : {
      primary: palette.accentPrimary,
      secondary: '#0d9488',
      tertiary: '#7c3aed',
      quaternary: '#d97706',
      positive: '#16a34a',
      negative: '#dc2626',
      neutral: '#64748b',
      grid: palette.strokeTertiary,
      axis: palette.textTertiary,
    }
  const sequence = [
    chartPalette.primary,
    chartPalette.secondary,
    chartPalette.tertiary,
    chartPalette.quaternary,
    chartPalette.positive,
    '#f97316',
    '#ec4899',
    chartPalette.neutral,
  ]
  const tokens = {
    bg: { editor: palette.bgEditor, chrome: palette.bgChrome, elevated: palette.bgElevated },
    text: {
      primary: palette.textPrimary,
      secondary: palette.textSecondary,
      tertiary: palette.textTertiary,
      quaternary: palette.textQuaternary,
      link: palette.textLink,
      onAccent: palette.textOnAccent,
    },
    fill: {
      primary: palette.fillPrimary,
      secondary: palette.fillSecondary,
      tertiary: palette.fillTertiary,
      quaternary: palette.fillQuaternary,
    },
    stroke: {
      primary: palette.strokePrimary,
      secondary: palette.strokeSecondary,
      tertiary: palette.strokeTertiary,
    },
    accent: {
      primary: palette.accentPrimary,
      control: palette.accentControl,
    },
    status: {
      success: palette.success,
      warn: palette.warn,
      error: palette.error,
      info: palette.info,
    },
    diff: {
      addedBg: palette.diffAddedBg,
      addedText: palette.diffAddedText,
      removedBg: palette.diffRemovedBg,
      removedText: palette.diffRemovedText,
    },
  }
  return {
    kind,
    ...tokens,
    tokens,
    palette,
    categories: isDark ? categoryPaletteDark : categoryPaletteLight,
    radius: RADIUS,
    typography: TYPOGRAPHY,
    chart: { palette: chartPalette, sequence },
  }
}

export const canvasTokens = buildTheme('dark', canvasPaletteDark)
export const canvasTokensLight = buildTheme('light', canvasPaletteLight)

export function resolveTheme(raw) {
  const fallbackDark = typeof window !== 'undefined' && typeof window.matchMedia === 'function'
    ? window.matchMedia('(prefers-color-scheme: dark)').matches
    : true
  const kind = raw?.kind === 'light' ? 'light' : raw?.kind === 'dark' ? 'dark' : fallbackDark ? 'dark' : 'light'
  const base = kind === 'light' ? canvasPaletteLight : canvasPaletteDark
  const overrides = {}
  if (raw && typeof raw.overrides === 'object' && raw.overrides) {
    for (const [key, value] of Object.entries(raw.overrides)) {
      if (typeof value === 'string' && value.trim() && key in base) overrides[key] = value.trim()
    }
  }
  return buildTheme(kind, base, overrides)
}

import { build } from 'esbuild'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client.js'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react', 'react/jsx-runtime'],
  define: { 'process.env.NODE_ENV': '"production"' },
  minify: true,
  legalComments: 'eof',
  metafile: true,
  write: false,
})

// The browser module table supplies React. Everything else ships in this bundle.
for (const output of Object.values(result.metafile.outputs)) {
  for (const entry of output.imports) {
    if (entry.external && !['react', 'react/jsx-runtime'].includes(entry.path)) {
      throw new Error(`Unexpected Client runtime import: ${entry.path}`)
    }
  }
}
const artifact = `// Generated by pnpm --filter dsh-message-actions build. Edit src/client.js instead.
/* oxlint-disable */
window.__ModuleLoader__.load({
  id: 'dsh-message-actions',
  factory(require) {
    const module = { exports: {} }
${result.outputFiles[0].text}
    return module.exports.default
  },
})
`

// Include each bundled dependency's license with the distributable artifact.
const licenses = new Map()
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes('node_modules/')) continue
  let dir = dirname(resolve(root, input))
  while (dir !== dirname(dir)) {
    let pkg
    try { pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8')) }
    catch (error) { if (error.code !== 'ENOENT') throw error }
    if (pkg) {
      if (!licenses.has(pkg.name)) {
        const license = (await readdir(dir)).find(name => /^licen[cs]e(?:[.-].*)?$/i.test(name))
        const text = license ? await readFile(join(dir, license), 'utf8') : `License: ${pkg.license}`
        licenses.set(pkg.name, `${pkg.name}@${pkg.version}\n${text.trim()}`)
      }
      break
    }
    dir = dirname(dir)
  }
}
await writeFile(join(root, 'lib/THIRD_PARTY_LICENSES.txt'), [...licenses].toSorted(([a], [b]) => a.localeCompare(b)).map(([, text]) => text).join('\n\n---\n\n') + '\n')
await writeFile(join(root, 'lib/client.js'), artifact)
console.log(`Built Client: ${Buffer.byteLength(artifact)} bytes; ${licenses.size} dependency licenses; React remains external.`)
